"""20个谜语连播给小橙子

用法：
    .venv/bin/python 工具脚本/20个谜语连播_给小橙子.py

功能：
    连续播放20个适合8岁孩子的谜语，每个谜语后有停顿时间让小橙子猜，
    然后公布答案，再继续下一个。
"""

import sys
import time
from pathlib import Path

project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from 书童程序.核心.语音模块 import VoiceEngine


RIDDLES = [
    ("身穿绿衣裳，肚里水汪汪，生的子儿多，个个黑脸膛。", "西瓜"),
    ("千条线，万条线，掉到水里看不见。", "雨"),
    ("远看山有色，近听水无声，春去花还在，人来鸟不惊。", "画"),
    ("五个兄弟，住在一起，名字不同，高矮不齐。", "手指"),
    ("小小诸葛亮，独坐中军帐，摆下八卦阵，专捉飞来将。", "蜘蛛"),
    ("小小一间房，有门没有窗，天天送客人，上上下下忙。", "电梯"),
    ("有头没有颈，有翅没有毛，无脚也能走，四海把家照。", "太阳"),
    ("耳朵长，尾巴短，只吃菜，不吃饭。", "兔子"),
    ("有方有圆又有长，你要喝水它帮忙。", "杯子"),
    ("独木造高楼，没瓦没砖头，人在水下走，水在人上流。", "雨伞"),
    ("身穿花衣爱打扮，一对翅膀光闪闪，不会唱歌爱跳舞，花丛里面玩得欢。", "蝴蝶"),
    ("一个小姑娘，生在水中央，身穿粉红衫，坐在绿船上。", "荷花"),
    ("白糖梅子真稀奇，也没核儿也没皮，正月十五沿街卖，过了正月没人提。", "元宵"),
    ("屋子方方，有门没窗，屋外热烘，屋里冰霜。", "冰箱"),
    ("上不怕水，下不怕火，家家厨房，都有一个。", "锅"),
    ("弟兄七八个，围着柱子坐，只要一分开，衣服就扯破。", "大蒜"),
    ("人脱衣服，它穿衣服，人脱帽子，它戴帽子。", "衣架"),
    ("身体多轻柔，逍遥漫天游，风来它就躲，雨来它带头。", "云"),
    ("颜色白如雪，身子硬如铁，一日洗三遍，夜晚柜中歇。", "碗"),
    ("身体细长，兄弟成双，光爱吃菜，不爱喝汤。", "筷子"),
]


def speak(text, wait=True):
    """播报文字"""
    engine = VoiceEngine()
    engine.speak(text)
    if wait:
        time.sleep(0.5)


def main():
    print("=" * 60)
    print("【20个谜语连播 · 给小橙子】")
    print("=" * 60)
    
    speak("小橙子，20个谜语连播开始啦！每个谜语之后，书童会停几秒让你猜，然后公布答案。准备好了吗？开始！", wait=False)
    time.sleep(3)
    
    for i, (riddle, answer) in enumerate(RIDDLES, 1):
        print(f"\n第 {i}/20 题：{riddle}")
        
        # 播放谜语
        speak(f"第{i}题。{riddle}", wait=False)
        
        # 等待小橙子猜
        print(f"等待猜谜中...")
        time.sleep(5)
        
        # 公布答案
        print(f"答案：{answer}")
        speak(f"答案是：{answer}。", wait=False)
        
        # 短暂停顿后进入下一题
        time.sleep(2)
    
    speak("小橙子，20个谜语全部播完啦！你猜对了几个？", wait=False)
    print("\n" + "=" * 60)
    print("【20个谜语连播完成】")
    print("=" * 60)


if __name__ == "__main__":
    sys.exit(main())
