  function getStoredLanguage() {
    try {
      const lang = localStorage.getItem(STORAGE_KEY);
      if (lang === 'zh' || lang === 'en') return lang;
    } catch (e) {}
    return 'zh';
  }

  function setStoredLanguage(lang) {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
  }

  function getText(key, replacements) {
    const lang = window.__bookboyLang || getStoredLanguage();
    const dict = translations[lang] || translations.zh;
    let text = dict[key];
    if (text === undefined) text = translations.zh[key];
    if (text === undefined) return key;
    if (replacements) {
      Object.keys(replacements).forEach(function (k) {
        text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), replacements[k]);
      });
    }
    return text;
  }

  function applyLanguage(lang) {
    if (!translations[lang]) lang = 'zh';
    window.__bookboyLang = lang;
    setStoredLanguage(lang);

    const html = document.documentElement;
    if (html) html.setAttribute('lang', lang === 'en' ? 'en' : 'zh-CN');

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      const key = el.getAttribute('data-i18n');
      const text = getText(key);
      if (text === undefined || text === null) return;
      const attr = el.getAttribute('data-i18n-attr');
      if (attr) {
        el.setAttribute(attr, text);
      } else {
        el.textContent = text;
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      const key = el.getAttribute('data-i18n-html');
      const text = getText(key);
      if (text !== undefined && text !== null) {
        el.innerHTML = text;
      }
    });

    document.querySelectorAll('[data-i18n-toggle]').forEach(function (btn) {
      btn.textContent = lang === 'en' ? 'EN/中' : '中/EN';
      btn.title = lang === 'en' ? 'Switch to Chinese' : 'Switch to English';
    });

    if (document.createEvent) {
      const evt = document.createEvent('Event');
      evt.initEvent('bookboyLanguageChanged', true, true);
      document.dispatchEvent(evt);
    }
  }

  function toggleLanguage() {
    const current = window.__bookboyLang || getStoredLanguage();
    applyLanguage(current === 'en' ? 'zh' : 'en');
  }

  window.bookboyI18n = {
    getText: getText,
    applyLanguage: applyLanguage,
    toggleLanguage: toggleLanguage,
    getStoredLanguage: getStoredLanguage,
    translations: translations
  };

  function init() {
    applyLanguage(getStoredLanguage());
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
